import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;

/**
 * Voxel assets for the growable hop crop.
 *
 * <p>Run from the project root with JDK 21:
 * {@code java tools/GenerateHops.java}
 *
 * <p>The bine is a single stem centred on the block. Leaves radiate from the
 * stem so they always stay attached to it, and the hop cones hang from the
 * underside of the outward leaves so every cone grows out of a leaf. Java
 * block models only accept {@code angle} values of -45/-22.5/0/22.5/45, so
 * diagonal leaves and their cones are the straight ones turned by +-45
 * degrees around the stem's centre line.</p>
 *
 * <p>Writes the eight-age blockstate, the four growth stages and the hop-seed
 * item model, and only owns those files.</p>
 */
public final class GenerateHops {
    static final Path ROOT = Path.of("src/main/resources/assets/samogon");
    static final String CREDIT =
            "Original voxel geometry and pixel textures for Moonshiner; generated by tools/GenerateHops.java";
    /** The bine and every rotation pivot sit on this line. */
    static final double CENTRE = 8.0;
    static final double STEM = 0.6;
    static final double LEAF_HALF = 0.85;
    static final double LEAF_THICKNESS = 0.9;

    record Box(double x1, double y1, double z1, double x2, double y2, double z2, String texture, Integer angle) {}

    public static void main(String[] args) throws Exception {
        writeBlockstate();
        writeModel("block/hops_stage0", stage(3.4, List.of(
                new Leaf('x', 1, 1.6, 2.6, null),
                new Leaf('x', -1, 1.6, 2.6, null)), true));
        writeModel("block/hops_stage1", stage(7.4, List.of(
                new Leaf('x', 1, 1.6, 3.4, null),
                new Leaf('x', -1, 1.6, 3.4, null),
                new Leaf('z', 1, 4.8, 3.0, null),
                new Leaf('z', -1, 4.8, 3.0, null)), true));
        writeModel("block/hops_stage2", stage(11.4, List.of(
                new Leaf('x', 1, 1.6, 4.0, null),
                new Leaf('x', -1, 1.6, 4.0, null),
                new Leaf('z', 1, 4.8, 3.4, null, true),
                new Leaf('z', -1, 4.8, 3.4, null, true),
                new Leaf('x', 1, 8.0, 3.0, null, true),
                new Leaf('x', -1, 8.0, 3.0, null, true)), true));
        writeModel("block/hops_stage3", stage(15.4, List.of(
                new Leaf('x', 1, 1.6, 4.2, null),
                new Leaf('x', -1, 1.6, 4.2, null),
                new Leaf('z', 1, 4.6, 3.6, null, true),
                new Leaf('z', -1, 4.6, 3.6, null, true),
                new Leaf('x', 1, 7.6, 3.4, 45, true),
                new Leaf('x', 1, 7.6, 3.4, -45, true),
                new Leaf('x', -1, 7.6, 3.4, 45, true),
                new Leaf('x', -1, 7.6, 3.4, -45, true),
                new Leaf('x', 1, 10.6, 3.2, null, true),
                new Leaf('x', -1, 10.6, 3.2, null, true),
                new Leaf('z', 1, 13.4, 2.8, null, true),
                new Leaf('z', -1, 13.4, 2.8, null, true)), true));
        writeSeedModel();
        System.out.println("Generated the hop crop blockstate, four growth stages and the seed model.");
    }

    /** A leaf that grows straight out of the stem; {@code cone} adds a hop cone under its tip. */
    record Leaf(char axis, int sign, double y, double length, Integer angle, boolean cone) {
        Leaf(char axis, int sign, double y, double length, Integer angle) {
            this(axis, sign, y, length, angle, false);
        }
    }

    static List<Box> stage(double stemTop, List<Leaf> leaves, boolean bud) {
        List<Box> boxes = new ArrayList<>();
        boxes.add(box(CENTRE - STEM, 0, CENTRE - STEM, CENTRE + STEM, stemTop, CENTRE + STEM, "green", null));
        for (Leaf leaf : leaves) {
            boxes.add(leafBox(leaf));
            if (leaf.cone()) boxes.add(coneBox(leaf));
        }
        if (bud) boxes.add(box(CENTRE - 0.45, stemTop, CENTRE - 0.45, CENTRE + 0.45, stemTop + 0.6,
                CENTRE + 0.45, "herb", null));
        return boxes;
    }

    static Box leafBox(Leaf leaf) {
        double half = LEAF_HALF;
        double inner = CENTRE + 0.1;
        double outer = inner + leaf.length();
        double thickness = LEAF_THICKNESS;
        double y = leaf.y();
        if (leaf.axis() == 'x') {
            if (leaf.sign() > 0) {
                return box(inner, y, CENTRE - half, outer, y + thickness, CENTRE + half, "herb", leaf.angle());
            }
            return box(2 * CENTRE - outer, y, CENTRE - half, 2 * CENTRE - inner, y + thickness,
                    CENTRE + half, "herb", leaf.angle());
        }
        if (leaf.sign() > 0) {
            return box(CENTRE - half, y, inner, CENTRE + half, y + thickness, outer, "herb", leaf.angle());
        }
        return box(CENTRE - half, y, 2 * CENTRE - outer, CENTRE + half, y + thickness,
                2 * CENTRE - inner, "herb", leaf.angle());
    }

    /** A cone tucked under the outer half of a leaf so it reads as growing out of it. */
    static Box coneBox(Leaf leaf) {
        double inner = CENTRE + 0.1;
        double outer = inner + leaf.length();
        double near = CENTRE - 0.65;
        double far = CENTRE + 0.65;
        double bottom = leaf.y() - 1.6;
        double top = leaf.y() + 0.2;
        if (leaf.axis() == 'x') {
            if (leaf.sign() > 0) {
                return box(outer - 1.7, bottom, near, outer - 0.2, top, far, "green", leaf.angle());
            }
            return box(2 * CENTRE - outer + 0.2, bottom, near, 2 * CENTRE - outer + 1.7, top,
                    far, "green", leaf.angle());
        }
        if (leaf.sign() > 0) {
            return box(near, bottom, outer - 1.7, far, top, outer - 0.2, "green", leaf.angle());
        }
        return box(near, bottom, 2 * CENTRE - outer + 0.2, far, top,
                2 * CENTRE - outer + 1.7, "green", leaf.angle());
    }

    static void writeBlockstate() throws Exception {
        StringBuilder json = new StringBuilder();
        json.append("{\n\t\"variants\": {\n");
        for (int age = 0; age <= 7; age++) {
            json.append("\t\t\"age=").append(age).append("\": {\"model\": \"samogon:block/hops_stage")
                    .append(age / 2).append("\"}");
            json.append(age == 7 ? "\n" : ",\n");
        }
        json.append("\t}\n}\n");
        write(ROOT.resolve("blockstates/hops.json"), json.toString());
    }

    static void writeModel(String name, List<Box> boxes) throws Exception {
        StringBuilder json = new StringBuilder();
        json.append("{\n");
        json.append("\t\"format_version\": \"26.3\",\n");
        json.append("\t\"credit\": \"").append(CREDIT).append("\",\n");
        json.append("\t\"parent\": \"minecraft:block/block\",\n");
        json.append("\t\"ambientocclusion\": false,\n");
        json.append("\t\"textures\": {\n");
        json.append("\t\t\"particle\": \"samogon:block/materials/herb\",\n");
        json.append("\t\t\"green\": \"samogon:block/materials/green\",\n");
        json.append("\t\t\"herb\": \"samogon:block/materials/herb\"\n");
        json.append("\t},\n");
        json.append("\t\"elements\": [\n");
        for (int i = 0; i < boxes.size(); i++) {
            Box box = boxes.get(i);
            json.append("\t\t{\n");
            json.append("\t\t\t\"from\": [").append(number(box.x1())).append(", ")
                    .append(number(box.y1())).append(", ").append(number(box.z1())).append("],\n");
            json.append("\t\t\t\"to\": [").append(number(box.x2())).append(", ")
                    .append(number(box.y2())).append(", ").append(number(box.z2())).append("],\n");
            if (box.angle() != null) {
                json.append("\t\t\t\"rotation\": {\"angle\": ").append(box.angle())
                        .append(", \"axis\": \"y\", \"origin\": [").append(number(CENTRE)).append(", 0, ")
                        .append(number(CENTRE)).append("]},\n");
            }
            json.append("\t\t\t\"faces\": {\n");
            String[] faces = {"north", "east", "south", "west", "up", "down"};
            for (int face = 0; face < faces.length; face++) {
                json.append("\t\t\t\t\"").append(faces[face])
                        .append("\": {\"uv\": [0, 0, 16, 16], \"texture\": \"#")
                        .append(box.texture()).append("\"}");
                json.append(face == faces.length - 1 ? "\n" : ",\n");
            }
            json.append("\t\t\t}\n");
            json.append("\t\t}");
            json.append(i == boxes.size() - 1 ? "\n" : ",\n");
        }
        json.append("\t]\n}\n");
        write(ROOT.resolve("models/" + name + ".json"), json.toString());
    }

    static void writeSeedModel() throws Exception {
        StringBuilder json = new StringBuilder();
        json.append("{\n");
        json.append("\t\"format_version\": \"26.3\",\n");
        json.append("\t\"credit\": \"").append(CREDIT).append("\",\n");
        json.append("\t\"parent\": \"minecraft:block/block\",\n");
        json.append("\t\"ambientocclusion\": false,\n");
        json.append("\t\"gui_light\": \"front\",\n");
        json.append("\t\"textures\": {\n");
        json.append("\t\t\"particle\": \"samogon:block/materials/grain\",\n");
        json.append("\t\t\"grain\": \"samogon:block/materials/grain\",\n");
        json.append("\t\t\"herb\": \"samogon:block/materials/herb\"\n");
        json.append("\t},\n");
        json.append("\t\"elements\": [\n");
        List<Box> seeds = List.of(
                box(4.0, 2.0, 5.0, 7.0, 4.0, 8.0, "grain", null),
                box(7.0, 2.0, 6.0, 10.0, 4.0, 9.0, "grain", null),
                box(5.0, 2.0, 9.0, 8.0, 4.0, 12.0, "grain", null),
                box(8.5, 2.0, 3.6, 11.0, 3.4, 5.8, "grain", null),
                box(3.0, 2.0, 8.4, 4.6, 3.2, 10.4, "grain", null),
                box(9.4, 2.0, 9.4, 11.4, 3.0, 11.4, "herb", null));
        for (int i = 0; i < seeds.size(); i++) {
            Box box = seeds.get(i);
            json.append("\t\t{\n");
            json.append("\t\t\t\"from\": [").append(number(box.x1())).append(", ")
                    .append(number(box.y1())).append(", ").append(number(box.z1())).append("],\n");
            json.append("\t\t\t\"to\": [").append(number(box.x2())).append(", ")
                    .append(number(box.y2())).append(", ").append(number(box.z2())).append("],\n");
            json.append("\t\t\t\"faces\": {\n");
            String[] faces = {"north", "east", "south", "west", "up", "down"};
            for (int face = 0; face < faces.length; face++) {
                json.append("\t\t\t\t\"").append(faces[face])
                        .append("\": {\"uv\": [0, 0, 16, 16], \"texture\": \"#")
                        .append(box.texture()).append("\"}");
                json.append(face == faces.length - 1 ? "\n" : ",\n");
            }
            json.append("\t\t\t}\n");
            json.append("\t\t}");
            json.append(i == seeds.size() - 1 ? "\n" : ",\n");
        }
        json.append("\t],\n");
        json.append("\t\"display\": {\n");
        json.append("\t\t\"thirdperson_righthand\": {\"rotation\": [75, 45, 0], \"translation\": [0, 2, 0], \"scale\": [0.5, 0.5, 0.5]},\n");
        json.append("\t\t\"thirdperson_lefthand\": {\"rotation\": [75, 45, 0], \"translation\": [0, 2, 0], \"scale\": [0.5, 0.5, 0.5]},\n");
        json.append("\t\t\"firstperson_righthand\": {\"rotation\": [0, 45, 0], \"translation\": [0, 1, 0], \"scale\": [0.55, 0.55, 0.55]},\n");
        json.append("\t\t\"firstperson_lefthand\": {\"rotation\": [0, -135, 0], \"translation\": [0, 1, 0], \"scale\": [0.55, 0.55, 0.55]},\n");
        json.append("\t\t\"ground\": {\"translation\": [0, 3, 0], \"scale\": [0.4, 0.4, 0.4]},\n");
        json.append("\t\t\"gui\": {\"rotation\": [25, -135, 0], \"scale\": [1.0, 1.0, 1.0]},\n");
        json.append("\t\t\"fixed\": {\"rotation\": [0, -180, 0], \"scale\": [0.7, 0.7, 0.7]}\n");
        json.append("\t}\n}\n");
        write(ROOT.resolve("models/item/hops_seeds.json"), json.toString());
    }

    static Box box(double x1, double y1, double z1, double x2, double y2, double z2, String texture, Integer angle) {
        return new Box(x1, y1, z1, x2, y2, z2, texture, angle);
    }

    static String number(double value) {
        if (value == Math.rint(value)) return Integer.toString((int) value);
        return Double.toString(value);
    }

    static void write(Path path, String text) throws Exception {
        Files.createDirectories(path.getParent());
        Files.writeString(path, text, StandardCharsets.UTF_8);
    }

    private GenerateHops() {}
}