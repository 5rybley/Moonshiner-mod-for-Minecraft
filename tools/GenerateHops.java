import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;

/**
 * Voxel assets for the growable hop crop.
 *
 * <p>Run from the project root with JDK 21:
 * {@code java tools/GenerateHops.java}
 *
 * <p>Writes the eight-age blockstate, the four growth stages and the hop-seed
 * item model. It only owns these files, so it never touches the rest of the
 * generated asset set.</p>
 */
public final class GenerateHops {
    static final Path ROOT = Path.of("src/main/resources/assets/samogon");
    static final String CREDIT =
            "Original voxel geometry and pixel textures for Moonshiner; generated by tools/GenerateHops.java";

    record Box(double x1, double y1, double z1, double x2, double y2, double z2, String texture) {}

    public static void main(String[] args) throws Exception {
        writeBlockstate();
        writeModel("block/hops_stage0", List.of(
                box(7.3, 0, 7.3, 8.7, 2.6, 8.7, "green"),
                box(4.8, 2.0, 7.2, 7.3, 3.0, 8.8, "herb"),
                box(8.7, 2.4, 7.2, 11.2, 3.4, 8.8, "herb"),
                box(7.6, 2.6, 7.6, 8.4, 4.0, 8.4, "herb")));
        writeModel("block/hops_stage1", List.of(
                box(7.3, 0, 7.3, 8.7, 7.4, 8.7, "green"),
                box(4.5, 2.0, 7.2, 7.3, 3.0, 8.8, "herb"),
                box(8.7, 2.8, 7.2, 11.5, 3.8, 8.8, "herb"),
                box(5.2, 4.8, 7.2, 7.3, 5.8, 8.8, "herb"),
                box(8.7, 5.6, 7.2, 10.8, 6.6, 8.8, "herb"),
                box(7.6, 7.4, 7.6, 8.4, 8.6, 8.4, "herb")));
        writeModel("block/hops_stage2", List.of(
                box(7.3, 0, 7.3, 8.7, 11.4, 8.7, "green"),
                box(4.2, 2.0, 7.2, 7.3, 3.0, 8.8, "herb"),
                box(8.7, 2.8, 7.2, 11.8, 3.8, 8.8, "herb"),
                box(4.8, 5.0, 7.2, 7.3, 6.0, 8.8, "herb"),
                box(8.7, 5.8, 7.2, 11.2, 6.8, 8.8, "herb"),
                box(5.4, 8.0, 7.2, 7.3, 9.0, 8.8, "herb"),
                box(8.7, 8.8, 7.2, 10.6, 9.8, 8.8, "herb"),
                box(7.6, 11.4, 7.6, 8.4, 12.8, 8.4, "herb")));
        writeModel("block/hops_stage3", List.of(
                box(7.3, 0, 7.3, 8.7, 15.4, 8.7, "green"),
                box(4.2, 2.2, 7.2, 7.3, 3.2, 8.8, "herb"),
                box(8.7, 3.0, 7.2, 11.8, 4.0, 8.8, "herb"),
                box(4.6, 5.2, 7.2, 7.3, 6.2, 8.8, "herb"),
                box(8.7, 6.0, 7.2, 11.4, 7.0, 8.8, "herb"),
                box(4.6, 8.2, 7.2, 7.3, 9.2, 8.8, "herb"),
                box(8.7, 9.0, 7.2, 11.4, 10.0, 8.8, "herb"),
                box(5.4, 11.2, 7.2, 7.3, 12.2, 8.8, "herb"),
                box(8.7, 12.0, 7.2, 10.6, 13.0, 8.8, "herb"),
                box(7.5, 9.4, 6.3, 8.5, 11.4, 7.3, "grain"),
                box(8.7, 11.0, 7.5, 9.7, 13.0, 8.5, "grain"),
                box(6.3, 12.2, 7.5, 7.3, 14.2, 8.5, "grain"),
                box(7.6, 15.4, 7.6, 8.4, 16.0, 8.4, "green")));
        writeSeedModel();
        System.out.println("Generated the hop crop blockstate, four growth stages and the seed model.");
    }

    static void writeBlockstate() throws Exception {
        StringBuilder json = new StringBuilder();
        json.append("{\n\t\"variants\": {\n");
        for (int age = 0; age <= 7; age++) {
            json.append("\t\t\"age=").append(age).append("\": {\"model\": \"samogon:block/hops_stage")
                    .append(age / 2).append("\"}");
            json.append(age == 7 ? "\n" : ",\n");
        }
        json.append("\t}\n}\n");
        write(ROOT.resolve("blockstates/hops.json"), json.toString());
    }

    static void writeModel(String name, List<Box> boxes) throws Exception {
        StringBuilder json = new StringBuilder();
        json.append("{\n");
        json.append("\t\"credit\": \"").append(CREDIT).append("\",\n");
        json.append("\t\"parent\": \"minecraft:block/block\",\n");
        json.append("\t\"ambientocclusion\": false,\n");
        json.append("\t\"textures\": {\n");
        json.append("\t\t\"particle\": \"samogon:block/materials/herb\",\n");
        json.append("\t\t\"green\": \"samogon:block/materials/green\",\n");
        json.append("\t\t\"herb\": \"samogon:block/materials/herb\",\n");
        json.append("\t\t\"grain\": \"samogon:block/materials/grain\"\n");
        json.append("\t},\n");
        json.append("\t\"elements\": [\n");
        for (int i = 0; i < boxes.size(); i++) {
            Box box = boxes.get(i);
            json.append("\t\t{\n");
            json.append("\t\t\t\"from\": [").append(number(box.x1())).append(", ")
                    .append(number(box.y1())).append(", ").append(number(box.z1())).append("],\n");
            json.append("\t\t\t\"to\": [").append(number(box.x2())).append(", ")
                    .append(number(box.y2())).append(", ").append(number(box.z2())).append("],\n");
            json.append("\t\t\t\"faces\": {\n");
            String[] faces = {"north", "east", "south", "west", "up", "down"};
            for (int face = 0; face < faces.length; face++) {
                json.append("\t\t\t\t\"").append(faces[face])
                        .append("\": {\"uv\": [0, 0, 16, 16], \"texture\": \"#")
                        .append(box.texture()).append("\"}");
                json.append(face == faces.length - 1 ? "\n" : ",\n");
            }
            json.append("\t\t\t}\n");
            json.append("\t\t}");
            json.append(i == boxes.size() - 1 ? "\n" : ",\n");
        }
        json.append("\t]\n}\n");
        write(ROOT.resolve("models/" + name + ".json"), json.toString());
    }

    static void writeSeedModel() throws Exception {
        StringBuilder json = new StringBuilder();
        json.append("{\n");
        json.append("\t\"credit\": \"").append(CREDIT).append("\",\n");
        json.append("\t\"parent\": \"minecraft:block/block\",\n");
        json.append("\t\"ambientocclusion\": false,\n");
        json.append("\t\"gui_light\": \"front\",\n");
        json.append("\t\"textures\": {\n");
        json.append("\t\t\"particle\": \"samogon:block/materials/grain\",\n");
        json.append("\t\t\"grain\": \"samogon:block/materials/grain\",\n");
        json.append("\t\t\"herb\": \"samogon:block/materials/herb\"\n");
        json.append("\t},\n");
        json.append("\t\"elements\": [\n");
        List<Box> seeds = List.of(
                box(4.0, 2.0, 5.0, 7.0, 4.0, 8.0, "grain"),
                box(7.0, 2.0, 6.0, 10.0, 4.0, 9.0, "grain"),
                box(5.0, 2.0, 9.0, 8.0, 4.0, 12.0, "grain"),
                box(8.5, 2.0, 3.6, 11.0, 3.4, 5.8, "grain"),
                box(3.0, 2.0, 8.4, 4.6, 3.2, 10.4, "grain"),
                box(9.4, 2.0, 9.4, 11.4, 3.0, 11.4, "herb"));
        for (int i = 0; i < seeds.size(); i++) {
            Box box = seeds.get(i);
            json.append("\t\t{\n");
            json.append("\t\t\t\"from\": [").append(number(box.x1())).append(", ")
                    .append(number(box.y1())).append(", ").append(number(box.z1())).append("],\n");
            json.append("\t\t\t\"to\": [").append(number(box.x2())).append(", ")
                    .append(number(box.y2())).append(", ").append(number(box.z2())).append("],\n");
            json.append("\t\t\t\"faces\": {\n");
            String[] faces = {"north", "east", "south", "west", "up", "down"};
            for (int face = 0; face < faces.length; face++) {
                json.append("\t\t\t\t\"").append(faces[face])
                        .append("\": {\"uv\": [0, 0, 16, 16], \"texture\": \"#")
                        .append(box.texture()).append("\"}");
                json.append(face == faces.length - 1 ? "\n" : ",\n");
            }
            json.append("\t\t\t}\n");
            json.append("\t\t}");
            json.append(i == seeds.size() - 1 ? "\n" : ",\n");
        }
        json.append("\t],\n");
        json.append("\t\"display\": {\n");
        json.append("\t\t\"thirdperson_righthand\": {\"rotation\": [75, 45, 0], \"translation\": [0, 2, 0], \"scale\": [0.5, 0.5, 0.5]},\n");
        json.append("\t\t\"thirdperson_lefthand\": {\"rotation\": [75, 45, 0], \"translation\": [0, 2, 0], \"scale\": [0.5, 0.5, 0.5]},\n");
        json.append("\t\t\"firstperson_righthand\": {\"rotation\": [0, 45, 0], \"translation\": [0, 1, 0], \"scale\": [0.55, 0.55, 0.55]},\n");
        json.append("\t\t\"firstperson_lefthand\": {\"rotation\": [0, -135, 0], \"translation\": [0, 1, 0], \"scale\": [0.55, 0.55, 0.55]},\n");
        json.append("\t\t\"ground\": {\"translation\": [0, 3, 0], \"scale\": [0.4, 0.4, 0.4]},\n");
        json.append("\t\t\"gui\": {\"rotation\": [25, -135, 0], \"scale\": [1.0, 1.0, 1.0]},\n");
        json.append("\t\t\"fixed\": {\"rotation\": [0, -180, 0], \"scale\": [0.7, 0.7, 0.7]}\n");
        json.append("\t}\n}\n");
        write(ROOT.resolve("models/item/hops_seeds.json"), json.toString());
    }

    static Box box(double x1, double y1, double z1, double x2, double y2, double z2, String texture) {
        return new Box(x1, y1, z1, x2, y2, z2, texture);
    }

    static String number(double value) {
        if (value == Math.rint(value)) return Integer.toString((int) value);
        return Double.toString(value);
    }

    static void write(Path path, String text) throws Exception {
        Files.createDirectories(path.getParent());
        Files.writeString(path, text, StandardCharsets.UTF_8);
    }

    private GenerateHops() {}
}